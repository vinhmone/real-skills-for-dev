#!/usr/bin/env node
// Regenerate files derived from the skills/ folder and the `groups` in upstreams.json:
//   - README.md skill tables (between the skills:start / skills:end markers)
//   - .claude-plugin/marketplace.json, which `npx skills add` reads to show skills grouped (one plugin per group)
//
//   node scripts/generate.mjs           # rewrite both
//   node scripts/generate.mjs --check   # exit 1 if either is out of date
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { listRepoSkills } from "./lib/skills.mjs";

const START = "<!-- skills:start (generated by `npm run generate`, do not edit) -->";
const END = "<!-- skills:end -->";
const README = "README.md";
const MARKETPLACE = ".claude-plugin/marketplace.json";

function loadConfig(root) {
  const config = JSON.parse(readFileSync(join(root, "upstreams.json"), "utf8"));
  const skills = listRepoSkills(root);
  const groups = config.groups ?? [];
  const known = new Set(groups.map((g) => g.folder));
  const unknown = [...new Set(skills.map((s) => s.group))].filter((g) => !known.has(g));
  if (unknown.length) throw new Error(`skills/${unknown.join(", skills/")} not listed in upstreams.json "groups"`);

  // Each skill belongs to exactly one installer group (the CLI can't show a skill twice): the first that matches.
  const installerGroups = (config.installerGroups ?? []).map((g) => ({ ...g, skills: [] }));
  for (const s of skills) {
    s.installerGroup = installerGroups.find((g) => (g.include ?? []).some((p) => matches(p, s.rel)));
    if (!s.installerGroup) throw new Error(`skills/${s.rel} matches no "installerGroups" entry in upstreams.json`);
    s.installerGroup.skills.push(s);
  }

  return {
    upstreams: config.upstreams ?? [],
    groups: groups.map((g) => ({ ...g, skills: skills.filter((s) => s.group === g.folder) })),
    installerGroups,
  };
}

/** `**` = everything, `dir/**` = anything under dir, otherwise an exact skill path (e.g. `ponytail/ponytail`). */
function matches(pattern, rel) {
  if (pattern === "**") return true;
  if (pattern.endsWith("/**")) return rel.startsWith(pattern.slice(0, -2));
  return rel === pattern;
}

export function renderReadme(root) {
  const readme = readFileSync(join(root, README), "utf8").replace(/\r\n/g, "\n");
  const s = readme.indexOf(START);
  const e = readme.indexOf(END);
  if (s < 0 || e < s) throw new Error(`README.md is missing the ${START} … ${END} markers`);

  const { upstreams, groups } = loadConfig(root);
  const body = groups.map((g, i) => {
    const upstream = upstreams.find((u) => u.dest === `skills/${g.folder}`);
    const lines = [`### ${i + 1}. ${g.title} (\`skills/${g.folder}\`)`, ""];
    if (upstream) lines.push(`Synced from <${upstream.repo}>.`, "");
    lines.push("| Skill | Installer group | Description |", "| --- | --- | --- |");
    for (const s of g.skills) {
      const desc = (s.meta.description ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
      lines.push(`| [\`${s.meta.name ?? s.folder}\`](skills/${s.rel}) | ${s.installerGroup.title} | ${desc} |`);
    }
    return lines.join("\n") + "\n";
  });

  return readme.slice(0, s + START.length) + "\n\n" + body.join("\n") + readme.slice(e);
}

export function renderMarketplace(root) {
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  const { installerGroups } = loadConfig(root);
  const manifest = {
    name: pkg.name,
    owner: { name: pkg.author },
    metadata: { description: pkg.description },
    plugins: installerGroups
      .filter((g) => g.skills.length)
      .map((g) => ({
        name: g.plugin,
        source: "./",
        description: g.description ?? g.title,
        strict: false,
        skills: g.skills.map((s) => `./skills/${s.rel}`),
      })),
  };
  return JSON.stringify(manifest, null, 2) + "\n";
}

const OUTPUTS = [
  [README, renderReadme],
  [MARKETPLACE, renderMarketplace],
];

export function generate(root) {
  for (const [file, render] of OUTPUTS) {
    const path = join(root, file);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, render(root));
  }
}

/** Files whose content differs from what would be generated. */
export function staleOutputs(root) {
  return OUTPUTS.filter(([file, render]) => {
    const path = join(root, file);
    return !existsSync(path) || readFileSync(path, "utf8").replace(/\r\n/g, "\n") !== render(root);
  }).map(([file]) => file);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  try {
    if (process.argv.includes("--check")) {
      const stale = staleOutputs(root);
      if (stale.length) {
        console.error(`✖ Out of date: ${stale.join(", ")} — run \`npm run generate\`.`);
        process.exit(1);
      }
      console.log("✓ Generated files are up to date");
    } else {
      generate(root);
      console.log(`✓ Updated ${OUTPUTS.map(([f]) => f).join(", ")}`);
    }
  } catch (e) {
    console.error(`✖ ${e.message}`);
    process.exit(1);
  }
}
